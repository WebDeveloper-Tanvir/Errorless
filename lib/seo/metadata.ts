import type { Metadata } from "next"
import { DEFAULT_DESCRIPTION, SITE_NAME } from "./site.ts"

export interface PageSeo {
  /** Final <title>. Keep it at or under 60 characters. */
  title: string
  /** Meta description. Keep it between 70 and 160 characters. */
  description: string
  /** Path starting with "/". Becomes the canonical URL and og:url. */
  path: string
  type?: "website" | "article"
  noindex?: boolean
  /** Optional absolute or root-relative image. Omit to use the generated opengraph-image of the route. */
  image?: { url: string; alt: string; width?: number; height?: number }
  /** True when the route has its own opengraph-image file, so no default image is added. */
  routeOwnsImage?: boolean
}

/** Generated by app/opengraph-image.tsx. Used for pages without their own social image. */
export const DEFAULT_OG_IMAGE = { url: "/opengraph-image", width: 1200, height: 630, alt: "Errorless: AI error debugger that finds the root cause" }

export const TITLE_MAX = 60
export const DESCRIPTION_MIN = 70
export const DESCRIPTION_MAX = 160

/**
 * One place that builds title, description, canonical, Open Graph and Twitter metadata,
 * so every page stays consistent. Relative URLs are resolved by metadataBase in app/layout.tsx.
 */
export function buildMetadata(p: PageSeo): Metadata {
  // A page-level openGraph object replaces the parent's, so the default image must be re-added here.
  const chosen = p.image ?? (p.routeOwnsImage ? undefined : DEFAULT_OG_IMAGE)
  const images = chosen ? [{ url: chosen.url, width: chosen.width, height: chosen.height, alt: chosen.alt }] : undefined
  return {
    title: { absolute: p.title },
    description: p.description,
    alternates: { canonical: p.path },
    robots: p.noindex ? { index: false, follow: false, googleBot: { index: false, follow: false } } : undefined,
    openGraph: {
      type: p.type ?? "website",
      siteName: SITE_NAME,
      locale: "en_US",
      url: p.path,
      title: p.title,
      description: p.description,
      ...(images ? { images } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: p.title,
      description: p.description,
      ...(images ? { images: images.map((i) => i.url) } : {}),
    },
  }
}

/** Metadata for private/transactional pages: never indexed, links not followed. */
export function privateMetadata(title: string): Metadata {
  return {
    title,
    description: DEFAULT_DESCRIPTION,
    robots: { index: false, follow: false, nocache: true, googleBot: { index: false, follow: false } },
  }
}

export interface SeoProblem {
  path: string
  problem: string
}

/** Lint helper used by tests: returns every way a page's SEO fields break our rules. */
export function lintSeo(p: PageSeo): string[] {
  const out: string[] = []
  if (!p.title.trim()) out.push("title is empty")
  if (p.title.length > TITLE_MAX) out.push(`title is ${p.title.length} chars (max ${TITLE_MAX})`)
  if (p.description.length < DESCRIPTION_MIN) out.push(`description is ${p.description.length} chars (min ${DESCRIPTION_MIN})`)
  if (p.description.length > DESCRIPTION_MAX) out.push(`description is ${p.description.length} chars (max ${DESCRIPTION_MAX})`)
  if (!p.path.startsWith("/")) out.push("path must start with /")
  if (/[?#]/.test(p.path)) out.push("canonical path must not contain query or hash")
  if (p.path.length > 1 && p.path.endsWith("/")) out.push("canonical path must not end with /")
  return out
}
